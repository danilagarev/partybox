import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import Ajv from 'ajv';
import { compile } from 'json-schema-to-typescript';
const schema = JSON.parse(
  await readFile(new URL('../schemas/rooms-v1.schema.json', import.meta.url), 'utf8'),
);
const examples = JSON.parse(
  await readFile(new URL('../examples/rooms-v1.json', import.meta.url), 'utf8'),
);
const ajv = new Ajv({ strict: true });
ajv.addSchema(schema);
test('room v1 examples conform and reject foreign actors and unsupported versions', () => {
  for (const [name, example] of Object.entries(examples)) {
    const validate = ajv.compile({ $ref: `${schema.$id}#/$defs/${name}` });
    assert.ok(validate(example), `${name}: ${ajv.errorsText(validate.errors)}`);
    assert.equal(validate({ ...example, playerId: 'foreign' }), false);
    assert.equal(validate({ ...example, protocolVersion: 2 }), false);
  }
  const validate = ajv.compile({ $ref: `${schema.$id}#/$defs/Enrollment` });
  for (const change of [
    { name: ' ' },
    { name: '\u0000name' },
    { name: '\ud800' },
    { name: 'a'.repeat(41) },
    { retryKey: 'short' },
    { requestId: 'anything' },
  ]) {
    assert.equal(validate({ ...examples.Enrollment, ...change }), false);
  }
  assert.ok(validate({ ...examples.Enrollment, name: 'Игрок 🎲' }));
});
test('generated room types match the schema', async () => {
  const actual = await readFile(new URL('../generated/rooms-v1.d.ts', import.meta.url), 'utf8');
  const expected = await compile(schema, 'RoomsV1', {
    unreachableDefinitions: true,
    ignoreMinAndMaxItems: true,
    style: { singleQuote: true, trailingComma: 'all', printWidth: 100 },
  });
  assert.equal(actual, expected);
});

test('OpenAPI definitions agree with the versioned schema', async () => {
  const api = JSON.parse(
    await readFile(new URL('../openapi-rooms-v1.json', import.meta.url), 'utf8'),
  );
  assert.deepEqual(
    api.components.schemas,
    JSON.parse(JSON.stringify(schema.$defs).replaceAll('#/$defs/', '#/components/schemas/')),
  );
  assert.equal(Object.keys(api.paths).length, 4);
});

test('generated Dart contract matches rooms-v1 schema', async () => {
  const dart = await readFile(
    new URL('../../../apps/mobile/lib/src/rooms/generated/room_schema.dart', import.meta.url),
    'utf8',
  );
  assert.equal(
    dart,
    `// GENERATED by packages/game-contracts/tool/dart.mjs. Do not edit.\nconst roomSchemaJson = r'''\n${JSON.stringify(schema, null, 2)}\n''';\n`,
  );
});
