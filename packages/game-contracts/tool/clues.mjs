import { readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';
import { format } from 'prettier';
const schema = JSON.parse(
  await readFile(new URL('../schemas/rooms-v4.schema.json', import.meta.url), 'utf8'),
);
await writeFile(
  new URL('../generated/rooms-v4.d.ts', import.meta.url),
  await compile(schema, 'RoomsV4', {
    unreachableDefinitions: true,
    ignoreMinAndMaxItems: true,
    style: { singleQuote: true, trailingComma: 'all', printWidth: 100 },
  }),
);
await writeFile(
  new URL('../../../apps/mobile/lib/src/rooms/generated/room_clues_schema.dart', import.meta.url),
  `// GENERATED by packages/game-contracts/tool/clues.mjs. Do not edit.\nconst roomCluesSchemaJson = r'''\n${JSON.stringify(schema, null, 2)}\n''';\n`,
);
const ref = (name) => ({ $ref: `#/components/schemas/${name}` });
const json = (name) => ({ 'application/json': { schema: ref(name) } });
const response = (name) => ({
  201: { description: 'Принято', content: json(name) },
  default: { description: 'Ошибка', content: json('V4Error') },
});
const body = (name) => ({ required: true, content: json(name) });
const roomId = {
  in: 'path',
  name: 'roomId',
  required: true,
  schema: { type: 'string', format: 'uuid' },
};
const paths = {
  '/v4/rooms': {
    post: { requestBody: body('V4Enrollment'), responses: response('V4EnrollmentResult') },
  },
  '/v4/rooms/join/{pin}': {
    post: {
      parameters: [
        {
          in: 'path',
          name: 'pin',
          required: true,
          schema: { type: 'string', pattern: '^[0-9]{6}$' },
        },
      ],
      requestBody: body('V4Enrollment'),
      responses: response('V4EnrollmentResult'),
    },
  },
  '/v4/rooms/{roomId}': {
    get: {
      security: [{ guestToken: [] }],
      parameters: [roomId],
      responses: {
        200: { description: 'Персональный snapshot', content: json('V4Snapshot') },
        default: { description: 'Ошибка', content: json('V4Error') },
      },
    },
  },
  '/v4/rooms/{roomId}/commands': {
    post: {
      security: [{ guestToken: [] }],
      parameters: [roomId],
      requestBody: body('V4Command'),
      responses: response('V4Ack'),
    },
  },
};
await writeFile(
  new URL('../openapi-rooms-v4.json', import.meta.url),
  await format(
    JSON.stringify({
      openapi: '3.1.0',
      info: { title: 'PartyBox — сетевая партия', version: '4.0.0' },
      paths,
      components: {
        securitySchemes: { guestToken: { type: 'http', scheme: 'bearer' } },
        schemas: JSON.parse(
          JSON.stringify(schema.$defs).replaceAll('#/$defs/', '#/components/schemas/'),
        ),
      },
    }),
    { parser: 'json', printWidth: 100 },
  ),
);
